#!/usr/bin/env python3
"""Normalize the native skill index to this repository's canonical bundles."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile


class RefreshError(Exception):
    """The native registry could not be safely normalized."""


def run_native(arguments: list[str]) -> str:
    try:
        result = subprocess.run(
            ['gentle-ai', 'skill-registry', *arguments],
            text=True, capture_output=True, check=False,
        )
    except OSError as error:
        raise RefreshError(f'Cannot execute gentle-ai: {error}') from error
    if result.returncode:
        detail = result.stderr.strip() or result.stdout.strip()
        raise RefreshError(f'gentle-ai {arguments[0]} failed ({result.returncode}): {detail}')
    return result.stdout


def cell(value: str) -> str:
    return ' '.join(value.split()).replace('|', r'\|').strip() or '—'


def canonical_rows(root: Path, raw: str) -> list[dict[str, str]]:
    try:
        rows = json.loads(raw)
    except json.JSONDecodeError as error:
        raise RefreshError(f'Invalid native registry JSON: {error}') from error
    if not isinstance(rows, list):
        raise RefreshError('Native registry list must be a JSON array.')
    canonical = root / '.agents' / 'skills'
    if canonical.is_symlink() or canonical.resolve() != canonical:
        raise RefreshError('The canonical .agents/skills directory must be physical and inside the repository.')
    selected = []
    for row in rows:
        if not isinstance(row, dict) or not all(
            isinstance(row.get(key), str) for key in ['name', 'path', 'description']
        ):
            raise RefreshError('Native registry entries require string name, path and description fields.')
        path = Path(row['path'])
        if not path.is_absolute():
            path = root / path
        try:
            resolved = path.resolve(strict=True)
            relative = resolved.relative_to(canonical)
        except (OSError, ValueError, RuntimeError):
            continue
        if len(relative.parts) != 2 or relative.name != 'SKILL.md' or not resolved.is_file():
            continue
        selected.append({
            'name': row['name'], 'description': row['description'],
            'path': resolved.relative_to(root).as_posix(),
        })
    return sorted(selected, key=lambda row: row['name'])


def render(rows: list[dict[str, str]]) -> bytes:
    lines = [
        '# Skill Registry — project-local', '',
        '<!-- Generated by .agents/skills/skill-registry/scripts/refresh.py; native metadata, project-only paths. -->', '',
        '## Sources scanned', '', '- .agents/skills', '', '## Contract', '',
        '**Delegator use only.** This registry is an index, not a summary. '
        'Select relevant skills and pass exact `SKILL.md` paths for subagents to read before work.', '',
        '`SKILL.md` remains the source of truth. Do not inject generated summaries or compact rules. '
        'Paths are relative to the repository root; resolve them against the selected repository, not the process directory.', '',
        '## Skills', '', '| Skill | Trigger / description | Scope | Path |',
        '| --- | --- | --- | --- |',
    ]
    for row in rows:
        lines.append(f"| `{cell(row['name'])}` | {cell(row['description'])} | project | `{cell(row['path'])}` |")
    lines.extend([
        '', '## Loading protocol', '',
        '1. Run `python3 .agents/skills/skill-registry/scripts/refresh.py` before consuming this index.',
        '2. Match task context and target files against the trigger/description column.',
        '3. Pass matching canonical `SKILL.md` paths under `## Skills to load before work`; read the full files.',
        '4. Report missing local skills instead of substituting a global installation.', '',
        '## Native hook limitation', '',
        'Global startup hooks still call native refresh. Native source changes or a forced refresh can overwrite '
        'this projection; run the project command again before reading it. Native cache hits retain the projection. '
        'This command does not modify or intercept global hooks.',
    ])
    return ('\n'.join(lines) + '\n').encode()


def atomic_write(path: Path, data: bytes) -> None:
    if path.exists() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix=f'.{path.name}.', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as handle:
            handle.write(data)
            os.fchmod(handle.fileno(), 0o644)
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def refresh(root: Path, force: bool) -> tuple[int, str]:
    destination = root / '.atl' / 'skill-registry.md'
    if not root.is_dir() or not ((root / '.git').exists() or (root / '.atl').is_dir()):
        raise RefreshError('Select a project root containing .git or .atl.')
    if (root / '.atl').is_symlink() or destination.is_symlink():
        raise RefreshError('The registry directory and file must not be symlinks.')
    previous = destination.read_bytes() if destination.exists() else None
    try:
        arguments = ['refresh', '--no-gitignore', '--cwd', str(root)]
        if force:
            arguments.append('--force')
        native_status = run_native(arguments)
        rows = canonical_rows(root, run_native(['list', '--json', '--cwd', str(root)]))
        atomic_write(destination, render(rows))
    except (RefreshError, OSError):
        if previous is None:
            destination.unlink(missing_ok=True)
        else:
            atomic_write(destination, previous)
        raise
    return len(rows), native_status.strip()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cwd', type=Path, default=Path(__file__).resolve().parents[4],
                        help='Repository root (defaults to the repository containing this script).')
    parser.add_argument('--force', action='store_true', help='Force the native metadata refresh.')
    args = parser.parse_args()
    try:
        count, status = refresh(args.cwd.resolve(), args.force)
    except (RefreshError, OSError) as error:
        print(f'Project skill registry failed: {error}', file=sys.stderr)
        return 1
    if status:
        print(status)
    print(f'Project skill registry normalized ({count} skills): .atl/skill-registry.md')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
